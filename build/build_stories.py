import re, json, sys
sys.path.insert(0, '.')
from stories_src import STORIES
KANJI = re.compile(r'[㐀-鿿々]')
TOK = re.compile(r'\{([^|{}]+)\|([^{}]+)\}')
bad = []
def parse(s, where):
    segs, pos = [], 0
    for m in TOK.finditer(s):
        plain = s[pos:m.start()]
        if KANJI.search(plain): bad.append((where, plain))
        if plain: segs.append(plain)
        base, rd = m.group(1), m.group(2)
        if not KANJI.search(base): bad.append((where, 'no kanji in ' + base))
        if KANJI.search(rd): bad.append((where, 'kanji in reading ' + rd))
        segs.append([base, rd]); pos = m.end()
    tail = s[pos:]
    if KANJI.search(tail): bad.append((where, tail))
    if tail: segs.append(tail)
    return segs
t = open('../site/kanji.js', encoding='utf-8').read()
KJ = json.loads(t[t.index('{'):t.rindex('}') + 1])
JL = {c: int(v[1]) for c, v in KJ.items() if len(v) > 1 and v[1]}
def auto_level(ks):
    # lowest JLPT level whose kanji (that level and easier) cover at least 85% of the story's kanji
    for n in (5, 4, 3, 2, 1):
        if sum(1 for c in ks if JL.get(c, 0) >= n) / len(ks) >= 0.85: return 'N%d' % n
    return 'N1'
out = []
for st in STORIES:
    title = parse(st['title'], st['id'] + ':title')
    paras = [{'jp': parse(jp, st['id']), 'en': en} for jp, en in st['paras']]
    allk = ''.join(''.join(s[0] for s in p['jp'] if isinstance(s, list)) for p in paras)
    ks = KANJI.findall(allk)
    chars = sum(len(s if isinstance(s, str) else s[0]) for p in paras for s in p['jp'])
    lvl = auto_level(ks)
    if st['level'] == 'N5':
        extra = [c for c in ks if JL.get(c, 0) < 5]
        if extra: bad.append((st['id'], 'non-N5 kanji ' + ''.join(extra)))
        lvl = 'N5'
    out.append({'id': st['id'], 'level': lvl, 'title': title, 'en': st['en'], 'paras': paras, 'kanji': ''.join(ks), 'chars': chars})
if bad:
    print('PROBLEMS:'); [print(' ', b) for b in bad]; sys.exit(1)
js = '// Original graded stories written for Yomeru. Generated by build/build_stories.py from build/stories_src.py.\nwindow.STORIES = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
open('../site/stories.js', 'w', encoding='utf-8').write(js)
out.sort(key=lambda s: -int(s['level'][1]))
for s in out: print(s['level'], s['id'], 'kanji occurrences', len(s['kanji']), 'unique', len(set(s['kanji'])), 'chars', s['chars'])
print('total', len(out), 'bytes', len(js.encode()))
